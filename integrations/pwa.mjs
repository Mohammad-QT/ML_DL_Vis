// Offline app support. After `astro build`, writes dist/sw.js: a service worker that precaches every built page,
// the _astro assets (scripts, styles, self-hosted fonts), icons, sample CSVs and notebooks.
// The cache name carries a hash of the build, so each deploy installs a fresh cache and deletes the old one.
import { createHash } from 'node:crypto';
import { readdir, readFile, writeFile } from 'node:fs/promises';
import { join, relative, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const SKIP = new Set(['sw.js', 'og.png', 'robots.txt', 'sitemap.xml']);

async function walk(dir) {
  const out = [];
  for (const e of await readdir(dir, { withFileTypes: true })) {
    const p = join(dir, e.name);
    if (e.isDirectory()) out.push(...(await walk(p)));
    else out.push(p);
  }
  return out;
}

/** @param {string} base e.g. '/ML_DL_Vis/' */
export function swSource(base, version, urls) {
  return `// Generated by integrations/pwa.mjs at build time. Do not edit.
const CACHE = 'mlv-${version}';
const BASE = ${JSON.stringify(base)};
const PRECACHE = ${JSON.stringify(urls)};

self.addEventListener('install', e => {
  e.waitUntil((async () => {
    const c = await caches.open(CACHE);
    // fetch fresh copies (not the HTTP cache) so a deploy never mixes old and new files
    await c.addAll(PRECACHE.map(u => new Request(u, { cache: 'reload' })));
    await self.skipWaiting();
  })());
});

self.addEventListener('activate', e => {
  e.waitUntil((async () => {
    for (const k of await caches.keys()) if (k.startsWith('mlv-') && k !== CACHE) await caches.delete(k);
    await self.clients.claim();
  })());
});

self.addEventListener('fetch', e => {
  const req = e.request;
  if (req.method !== 'GET') return;
  const url = new URL(req.url);
  if (url.origin !== location.origin || !url.pathname.startsWith(BASE)) return;

  // pages: network first so new deploys show up at once; the cached copy when offline
  if (req.mode === 'navigate') {
    e.respondWith((async () => {
      const c = await caches.open(CACHE);
      try {
        const res = await fetch(req);
        if (res.ok) c.put(url.pathname, res.clone());
        return res;
      } catch {
        return (await c.match(url.pathname, { ignoreSearch: true, ignoreVary: true }))
          || (await c.match(url.pathname.replace(/\\/?$/, '/'), { ignoreSearch: true, ignoreVary: true }))
          || (await c.match(BASE + '404.html', { ignoreVary: true }))
          || Response.error();
      }
    })());
    return;
  }

  // everything else is fingerprinted or rarely changes: cache first, then network (and keep a copy).
  // ignoreVary: servers may send "Vary: Origin", and font requests carry an Origin header the precache requests lacked
  e.respondWith((async () => {
    const c = await caches.open(CACHE);
    const hit = await c.match(req, { ignoreSearch: true, ignoreVary: true });
    if (hit) return hit;
    const res = await fetch(req);
    if (res.ok && res.type === 'basic') c.put(req, res.clone());
    return res;
  })());
});
`;
}

/** @returns {import('astro').AstroIntegration} */
export default function pwa() {
  let base = '/';
  return {
    name: 'mlv-pwa',
    hooks: {
      'astro:config:done': ({ config }) => { base = config.base.replace(/\/?$/, '/'); },
      'astro:build:done': async ({ dir, logger }) => {
        const root = fileURLToPath(dir);
        const files = (await walk(root)).map(f => relative(root, f).split(sep).join('/')).filter(f => !SKIP.has(f)).sort();
        const hash = createHash('sha256').update(swSource(base, '', [])); // a change to the worker's own logic also renews the cache
        const urls = [];
        for (const f of files) {
          hash.update(f).update(await readFile(join(root, f)));
          // pages are requested as their folder URL (trailingSlash: 'always'); 404.html stays a file
          urls.push(base + (f === 'index.html' ? '' : f.endsWith('/index.html') ? f.slice(0, -'index.html'.length) : f));
        }
        const version = hash.digest('hex').slice(0, 12);
        await writeFile(join(root, 'sw.js'), swSource(base, version, urls));
        logger.info(`sw.js: ${urls.length} files precached (cache mlv-${version})`);
      },
    },
  };
}
